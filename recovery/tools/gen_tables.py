"""Precomputed constants for pq_recovery.

  python tools/gen_tables.py          writes src/secp_table.cairo and checks the constants in
                                      src/bip32.cairo (HMAC "Bitcoin seed" pad states)

secp_table: signed comb table. Row i (0 <= i < 128) is the affine point
(2^224 + sum_{j<7} s_j 2^(32 j)) * G, s_j = +1 if bit j of i is set else -1, packed into three felts:
x.low + (x.high mod 2^123) 2^128, y.low + (y.high mod 2^123) 2^128, (x.high >> 123) + 32 (y.high >> 123).
"""
import hashlib
import hmac
import os
import re
import struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src")
P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
GX = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
GY = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8
PRIME = 2**251 + 17 * 2**192 + 1  # STARK field


def add(p1, p2):
    if p1 is None:
        return p2
    if p2 is None:
        return p1
    (x1, y1), (x2, y2) = p1, p2
    if x1 == x2:
        if (y1 + y2) % P == 0:
            return None
        lam = 3 * x1 * x1 * pow(2 * y1, -1, P) % P
    else:
        lam = (y2 - y1) * pow(x2 - x1, -1, P) % P
    x3 = (lam * lam - x1 - x2) % P
    return (x3, (lam * (x1 - x3) - y1) % P)


def mul(k, pt):
    r = None
    while k:
        if k & 1:
            r = add(r, pt)
        pt = add(pt, pt)
        k >>= 1
    return r


def signed_scalar(i):
    return 2**224 + sum((1 if i >> j & 1 else -1) * 2 ** (32 * j) for j in range(7))


def read(name):
    with open(os.path.join(ROOT, name)) as f:
        return f.read()


def u64_array(text, name, typ):
    m = re.search(r"const %s: \[%s; \d+\] = \[(.*?)\];" % (name, typ), text, re.S)
    return [int(x, 16) for x in m.group(1).replace("\n", " ").split(",") if x.strip()]


def sha512_state_after(block, k512, h512):
    """SHA-512 state after compressing one 128-byte block."""
    mask = 2**64 - 1
    rotr = lambda x, n: ((x >> n) | (x << (64 - n))) & mask
    w = list(struct.unpack(">16Q", block))
    for t in range(16, 80):
        s0 = rotr(w[t - 15], 1) ^ rotr(w[t - 15], 8) ^ (w[t - 15] >> 7)
        s1 = rotr(w[t - 2], 19) ^ rotr(w[t - 2], 61) ^ (w[t - 2] >> 6)
        w.append((w[t - 16] + s0 + w[t - 7] + s1) & mask)
    a, b, c, d, e, f, g, h = h512
    for i in range(80):
        t1 = (h + (rotr(e, 14) ^ rotr(e, 18) ^ rotr(e, 41)) + ((e & f) ^ (~e & g)) + k512[i] + w[i]) & mask
        t2 = ((rotr(a, 28) ^ rotr(a, 34) ^ rotr(a, 39)) + ((a & b) ^ (a & c) ^ (b & c))) & mask
        h, g, f, e, d, c, b, a = g, f, e, (d + t1) & mask, c, b, a, (t1 + t2) & mask
    return [(x + y) & mask for x, y in zip(h512, [a, b, c, d, e, f, g, h])]


def check_hmac_states():
    consts = read("constants.cairo")
    k512, h512 = u64_array(consts, "K512", "u64"), u64_array(consts, "H512", "u64")
    abc = b"abc\x80" + b"\0" * 108 + (24).to_bytes(16, "big")
    assert b"".join(x.to_bytes(8, "big") for x in sha512_state_after(abc, k512, h512)) == hashlib.sha512(b"abc").digest()
    key = b"Bitcoin seed".ljust(128, b"\0")
    ipad = sha512_state_after(bytes(b ^ 0x36 for b in key), k512, h512)
    opad = sha512_state_after(bytes(b ^ 0x5C for b in key), k512, h512)
    bip32 = read("bip32.cairo")
    assert u64_array(bip32, "BTC_IPAD_STATE", "u128") == ipad, "BTC_IPAD_STATE"
    assert u64_array(bip32, "BTC_OPAD_STATE", "u128") == opad, "BTC_OPAD_STATE"
    # the states reproduce hashlib's HMAC
    msg = bytes(range(64))
    inner = hashlib.sha512(bytes(b ^ 0x36 for b in key) + msg).digest()
    assert hashlib.sha512(bytes(b ^ 0x5C for b in key) + inner).digest() == hmac.new(b"Bitcoin seed", msg, hashlib.sha512).digest()


def write_table():
    m123 = 2**123 - 1
    rows = []
    for i in range(128):
        x, y = mul(signed_scalar(i) % N, (GX, GY))
        xl, xh, yl, yh = x & (2**128 - 1), x >> 128, y & (2**128 - 1), y >> 128
        row = (xl + (xh & m123) * 2**128, yl + (yh & m123) * 2**128, (xh >> 123) + (yh >> 123) * 32)
        assert row[0] < PRIME and row[1] < PRIME and row[2] < 1024
        rows.append(row)
    lines = [
        "//! Generated by tools/gen_tables.py. Do not edit.",
        "//! secp256k1 signed comb table. Point i in 0..128 is",
        "//! (2^224 + sum_{j < 7} s_j 2^(32 j)) * G with s_j = +1 if bit j of i is set, else -1,",
        "//! in affine coordinates, packed into the three felts of row i:",
        "//!   x.low + (x.high mod 2^123) * 2^128, y.low + (y.high mod 2^123) * 2^128,",
        "//!   (x.high >> 123) + 32 * (y.high >> 123).",
        "",
        "pub const SECP_COMB: [[felt252; 3]; %d] = [" % len(rows),
    ]
    lines += ["    [0x%x, 0x%x, 0x%x]," % r for r in rows]
    lines += ["];", ""]
    with open(os.path.join(ROOT, "secp_table.cairo"), "w", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    check_hmac_states()
    write_table()
    print("ok: HMAC pad states checked, secp_table.cairo written")
