// Writes the cairo-test fixture for key rotation: the same throwaway keys as
// migration_fixture.mjs, a second Falcon key, and the rotation proofs built by the kit, i.e.
// hybrid signatures by the key pair after the rotation over rotation_hash(ecdsa_pk, falcon_pk).
import { ec, num } from "starknet";
import { readFileSync, writeFileSync } from "node:fs";
import { falcon512, makeNtt, publicKeyFelts } from "./falcon_adapter.mjs";
import { hybridSignature, rotationHash } from "./pq_account_kit.mjs";
import { ROOTS, ROTATION_FIXTURE as FIXTURE } from "./config.mjs";

const ntt = makeNtt(JSON.parse(readFileSync(ROOTS, "utf8")));
const ecdsaKey = (priv) => ({ ecdsaPrivateKey: priv, ecdsaPublicKey: num.toHex(ec.starkCurve.getStarkKey(priv)) });
const falconKey = (fill) => {
  const { publicKey, secretKey } = falcon512.keygen(new Uint8Array(48).fill(fill));
  return { falconPublicKey: publicKey, falconSecretKey: secretKey, falconFelts: publicKeyFelts(publicKey, ntt).map(num.toHex) };
};

// Same seeds as migration_fixture.mjs (ECDSA_PK, WRONG_ECDSA_PK, falcon_pk()), plus Falcon key B.
const falconA = falconKey(7);
const falconB = falconKey(8);
const ecdsaOld = ecdsaKey("0x5eed03");
const ecdsaNew = ecdsaKey("0x5eed04");

function rotation(keys) {
  const message = rotationHash(keys.ecdsaPublicKey, keys.falconFelts);
  return { message, proof: hybridSignature(message, keys) };
}

const falconRotation = rotation({ ...ecdsaOld, ...falconB });
const ecdsaRotation = rotation({ ...ecdsaNew, ...falconA });

const arr = (xs) => xs.map((x) => `        ${num.toHex(x)},`).join("\n");
writeFileSync(FIXTURE, `//! Fixture for key rotation, generated by signer/rotation_fixture.mjs.
//! Same throwaway keys as tests_wallets_fixture.cairo, plus Falcon key B. Each proof is a hybrid
//! signature by the key pair after the rotation over rotation_hash(ecdsa_pk, falcon_pk).

/// Falcon rotation: ECDSA_PK stays, the Falcon key becomes falcon_pk_b().
pub const FALCON_ROTATION_HASH: felt252 = ${falconRotation.message};
/// ECDSA rotation: the ECDSA key becomes WRONG_ECDSA_PK, falcon_pk() stays.
pub const ECDSA_ROTATION_HASH: felt252 = ${ecdsaRotation.message};

pub fn falcon_pk_b() -> Array<felt252> {
    array![
${arr(falconB.falconFelts)}
    ]
}

pub fn falcon_rotation_proof() -> Array<felt252> {
    array![
${arr(falconRotation.proof)}
    ]
}

pub fn ecdsa_rotation_proof() -> Array<felt252> {
    array![
${arr(ecdsaRotation.proof)}
    ]
}
`);
console.log("ecdsa pk:", ecdsaOld.ecdsaPublicKey, " new ecdsa pk:", ecdsaNew.ecdsaPublicKey);
console.log("falcon rotation hash:", falconRotation.message, " ecdsa rotation hash:", ecdsaRotation.message);
console.log("fixture written:", FIXTURE);
