// Generates the SHA-256 / SHA-512 round constants and initial hashes for pq-recovery (Cairo),
// from their definitions (fractional parts of square and cube roots of the first primes), and
// the grindKey limit for the STARK curve order.
import { writeFileSync } from "node:fs";
import { RECOVERY_DIR } from "./config.mjs";

const primes = [];
for (let n = 2; primes.length < 80; n++) if (primes.every((p) => n % p)) primes.push(n);
const iroot = (x, k) => { // floor(x^(1/k)) for BigInt
  let r = BigInt(Math.floor(Number(x) ** (1 / k))) || 1n;
  for (;;) { const next = ((BigInt(k) - 1n) * r + x / r ** BigInt(k - 1)) / BigInt(k); if (next >= r) break; r = next; }
  while ((r + 1n) ** BigInt(k) <= x) r++;
  while (r ** BigInt(k) > x) r--;
  return r;
};
const frac = (p, k, bits) => iroot(BigInt(p) << BigInt(k * bits), k) & ((1n << BigInt(bits)) - 1n);
const K512 = primes.slice(0, 80).map((p) => frac(p, 3, 64));
const H512 = primes.slice(0, 8).map((p) => frac(p, 2, 64));
const K256 = primes.slice(0, 64).map((p) => frac(p, 3, 32));
const H256 = primes.slice(0, 8).map((p) => frac(p, 2, 32));
if (K512[0] !== 0x428a2f98d728ae22n || H512[0] !== 0x6a09e667f3bcc908n || K256[63] !== 0xc67178f2n || H256[7] !== 0x5be0cd19n) throw new Error("constant check failed");

const N_STARK = 0x800000000000010ffffffffffffffffb781126dcae7b2321e66a241adc64d2fn;
const LIMIT = (1n << 256n) - ((1n << 256n) % N_STARK);
const hex = (x) => "0x" + x.toString(16);
const arr = (xs, t) => `[\n${xs.map((x) => `    ${hex(x)},`).join("\n")}\n]`;
writeFileSync(`${RECOVERY_DIR}/src/constants.cairo`,`//! Generated by signer/recovery_constants.mjs from the SHA-2 definitions. Do not edit.

pub const K512: [u64; 80] = ${arr(K512)};
pub const H512: [u64; 8] = ${arr(H512)};
pub const K256: [u32; 64] = ${arr(K256)};
pub const H256: [u32; 8] = ${arr(H256)};

/// 2^256 - (2^256 mod n), n = STARK curve order (grindKey rejection bound).
pub const GRIND_LIMIT: u256 = ${hex(LIMIT)};
pub const STARK_ORDER: u256 = ${hex(N_STARK)};
`);
console.log("constants written; limit", hex(LIMIT));
