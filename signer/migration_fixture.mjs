// Writes the cairo-test fixture for wallet migrations (Argent-style perform_upgrade and
// Braavos-style upgrade + migrate): fixed throwaway ECDSA + noble Falcon-512 keys and a
// key-possession proof, i.e. a hybrid signature over registration_hash(ecdsa_pk, falcon_pk).
import { ec, hash, num, shortString } from "starknet";
import { readFileSync, writeFileSync } from "node:fs";
import { falcon512, hashToMessage, makeNtt, publicKeyFelts, signatureFelts, signTxHash } from "./falcon_adapter.mjs";
import { ROOTS, WALLETS_FIXTURE as FIXTURE } from "./config.mjs";

const DOMAIN = "starknet-pq-register-v1";

export function registrationHash(ecdsaPublicKey, falconFelts) {
  return hash.computePoseidonHashOnElements([shortString.encodeShortString(DOMAIN), ecdsaPublicKey, ...falconFelts]);
}

const ntt = makeNtt(JSON.parse(readFileSync(ROOTS, "utf8")));
const ecdsaPriv = "0x5eed03";
const otherPriv = "0x5eed04";
const ecdsaPub = num.toHex(ec.starkCurve.getStarkKey(ecdsaPriv));
const { publicKey, secretKey } = falcon512.keygen(new Uint8Array(48).fill(7));
const falconPk = publicKeyFelts(publicKey, ntt);

const message = registrationHash(ecdsaPub, falconPk);
const e = ec.starkCurve.sign(num.toHex(message), ecdsaPriv);
const bad = ec.starkCurve.sign(num.toHex(message), otherPriv);
const sig = signTxHash(BigInt(message), secretKey);
console.log("noble verify:", falcon512.verify(sig, hashToMessage(BigInt(message)), publicKey));
const falconSig = signatureFelts(sig, publicKey);

const arr = (xs) => xs.map((x) => `        ${num.toHex(x)},`).join("\n");
writeFileSync(FIXTURE, `//! Fixture for wallet migrations, generated by signer/migration_fixture.mjs.
//! Throwaway test keys: STARK-curve ECDSA + Falcon-512 (@noble/post-quantum, SHAKE-256).
//! PROOF is a hybrid signature over registration_hash(ECDSA_PK, falcon_pk()).

pub const ECDSA_PK: felt252 = ${ecdsaPub};
pub const REGISTRATION_HASH: felt252 = ${num.toHex(message)};
pub const ECDSA_R: felt252 = ${num.toHex(e.r)};
pub const ECDSA_S: felt252 = ${num.toHex(e.s)};
/// ECDSA signature over the same hash by a different key.
pub const WRONG_ECDSA_R: felt252 = ${num.toHex(bad.r)};
pub const WRONG_ECDSA_S: felt252 = ${num.toHex(bad.s)};

pub fn falcon_pk() -> Array<felt252> {
    array![
${arr(falconPk)}
    ]
}

pub fn falcon_sig() -> Array<felt252> {
    array![
${arr(falconSig)}
    ]
}
`);
console.log("ecdsa pk:", ecdsaPub, " registration hash:", num.toHex(message), " falcon felts:", falconPk.length, falconSig.length);
console.log("fixture written:", FIXTURE);
