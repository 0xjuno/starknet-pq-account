// Offline check of the browser signing path, before spending any testnet STRK:
//   1. noble Falcon-512 keygen + sign over the tx-hash bytes; noble verify
//   2. JS adapter -> on-chain felts; independently recomputed in Python (falcon.py) and compared
//   3. writes a cairo-test fixture so the real on-chain SHAKE verifier checks the signature
import { ec, num } from "starknet";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { BROWSER_FIXTURE, FALCON_PY, PY, ROOTS, SCRIPTS, SIGNER_DIR } from "./config.mjs";
import { decodePublicKey, decodeSignature, falcon512, hashToMessage, makeNtt, publicKeyFelts, signatureFelts, signTxHash } from "./falcon_adapter.mjs";

const FIXTURE = BROWSER_FIXTURE;

if (!existsSync(ROOTS)) {
  const r = spawnSync(PY, ["-I", `${SCRIPTS}/export_ntt_roots.py`, "--falcon-py", FALCON_PY, "--out", ROOTS], { encoding: "utf8" });
  if (r.status !== 0) throw new Error(r.stderr);
}
const ntt = makeNtt(JSON.parse(readFileSync(ROOTS, "utf8")));

// 1. browser-side primitives
const { publicKey, secretKey } = falcon512.keygen();
const txHash = BigInt("0x" + randomBytes(31).toString("hex"));
const sig = signTxHash(txHash, secretKey);
console.log("noble verify:", falcon512.verify(sig, hashToMessage(txHash), publicKey), " sig bytes:", sig.length);

// 2. JS adapter vs Python recomputation
const jsPk = publicKeyFelts(publicKey, ntt);
const jsSig = signatureFelts(sig, publicKey);
const { nonce, s2 } = decodeSignature(sig);
const r = spawnSync(PY, ["-I", `${SCRIPTS}/check_noble_vs_onchain.py`, "--falcon-py", FALCON_PY, "--signer-dir", SIGNER_DIR], {
  input: JSON.stringify({ hash: num.toHex(txHash), nonce_hex: Buffer.from(nonce).toString("hex"), s2, h: decodePublicKey(publicKey) }),
  encoding: "utf8", maxBuffer: 20e6,
});
if (r.status !== 0) throw new Error(r.stderr);
const py = JSON.parse(r.stdout);
const same = (a, b) => a.length === b.length && a.every((v, i) => BigInt(v) === BigInt(b[i]));
console.log("python on-chain rule accepts:", py.ok, " norm:", py.norm, "(bound 34034726)");
console.log("public key felts match:", same(jsPk, py.pkFelts), " signature felts match:", same(jsSig, py.sigFelts), " felts:", jsPk.length, jsSig.length);

// 3. cairo-test fixture: hybrid = test ECDSA key + this browser Falcon signature, same hash
const ecdsaPriv = "0x" + randomBytes(31).toString("hex");
const ecdsaPub = num.toHex(ec.starkCurve.getStarkKey(ecdsaPriv));
const e = ec.starkCurve.sign(num.toHex(txHash), ecdsaPriv);
const arr = (xs) => xs.map((x) => `        ${num.toHex(x)},`).join("\n");
writeFileSync(FIXTURE, `//! Browser-signed fixture: Falcon-512 signature produced by @noble/post-quantum (pure JS)
//! and converted by signer/falcon_adapter.mjs, checked by the on-chain SHAKE-256 verifier.
//! Generated by signer/browser_signer_check.mjs with throwaway test keys.

use pqbench_falcon_512::Falcon512ShakeVerifier;
use crate::hybrid::verify_hybrid;

const MSG: felt252 = ${num.toHex(txHash)};
const ECDSA_PK: felt252 = ${ecdsaPub};
const ECDSA_R: felt252 = ${num.toHex(e.r)};
const ECDSA_S: felt252 = ${num.toHex(e.s)};

fn falcon_pk() -> Array<felt252> {
    array![
${arr(jsPk)}
    ]
}

fn falcon_sig() -> Array<felt252> {
    array![
${arr(jsSig)}
    ]
}

#[test]
fn browser_falcon_signature_passes_shake_verifier() {
    assert!(Falcon512ShakeVerifier::verify(MSG, falcon_pk().span(), falcon_sig().span()));
}

#[test]
fn browser_falcon_signature_wrong_message_fails() {
    assert!(!Falcon512ShakeVerifier::verify(MSG + 1, falcon_pk().span(), falcon_sig().span()));
}

#[test]
fn browser_hybrid_signature_passes() {
    let mut sig = array![ECDSA_R, ECDSA_S];
    for f in falcon_sig() {
        sig.append(f);
    }
    assert!(verify_hybrid::<Falcon512ShakeVerifier>(MSG, ECDSA_PK, falcon_pk().span(), sig.span()));
}
`);
console.log("fixture written:", FIXTURE);
