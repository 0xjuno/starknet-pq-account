// Writes pq-recovery test vectors (Cairo tests + scarb execute argument files) from the same JS
// derivation the wallets use (pq_keys.mjs), so the Cairo program is checked against it.
import { mnemonicToSeedSync } from "@scure/bip39";
import { sha256, sha512 } from "@noble/hashes/sha2";
import { hmac } from "@noble/hashes/hmac";
import { bytesToHex } from "@noble/hashes/utils";
import { deriveAccountKeys } from "./pq_keys.mjs";
import { writeFileSync, mkdirSync } from "node:fs";
import { RECOVERY_DIR as OUT } from "./config.mjs";
const MNEMONIC = "test test test test test test test test test test test junk"; // Hardhat default, public
const seed = mnemonicToSeedSync(MNEMONIC);
const words = [];
for (let i = 0; i < 64; i += 8) words.push("0x" + bytesToHex(seed.slice(i, i + 8)));
const pq = deriveAccountKeys(MNEMONIC, 0, "pq").ecdsaPublicKey;
const argent = deriveAccountKeys(MNEMONIC, 0, "argentx").ecdsaPublicKey;
const enc = (s) => new TextEncoder().encode(s);
const hx = (b) => "0x" + bytesToHex(b);
const bytesArr = (b) => `array![${Array.from(b).map((x) => "0x" + x.toString(16)).join(", ")}]`;

const binding = "0x" + bytesToHex(sha256(enc("new falcon key commitment"))).slice(0, 62);
const tests = `//! Generated by signer/recovery_vectors.mjs. Do not edit.
use crate::bip32::account_stark_key;
use crate::secp256k1::mul_g;
use crate::sha2::{hmac_sha512, sha256, sha512, words64_to_bytes};

fn seed() -> Array<u8> {
    words64_to_bytes(array![${words.join(", ")}].span())
}

#[test]
fn sha256_abc() {
    assert_eq!(sha256(array![0x61, 0x62, 0x63].span()), ${bytesArr(sha256(enc("abc")))});
}

#[test]
fn sha512_abc() {
    assert_eq!(sha512(array![0x61, 0x62, 0x63].span()), ${bytesArr(sha512(enc("abc")))});
}

#[test]
fn sha512_two_blocks() {
    let mut data: Array<u8> = array![];
    let mut i: u32 = 0;
    while i != 200 {
        data.append((i % 256).try_into().unwrap());
        i += 1;
    }
    assert_eq!(sha512(data.span()), ${bytesArr(sha512(Uint8Array.from({ length: 200 }, (_, i) => i % 256)))});
}

#[test]
fn hmac_sha512_rfc4231_case2() {
    let key: Array<u8> = ${bytesArr(enc("Jefe"))};
    let data: Array<u8> = ${bytesArr(enc("what do ya want for nothing?"))};
    assert_eq!(hmac_sha512(key.span(), data.span()), ${bytesArr(hmac(sha512, enc("Jefe"), enc("what do ya want for nothing?")))});
}

#[test]
fn secp256k1_two_g() {
    let (x, _) = mul_g(2);
    assert_eq!(x, 0xc6047f9441ed7d6d3045406e95c07cd85c778e4b8cef3ca7abac09b95c709ee5);
}

#[test]
fn braavos_profile_matches_wallet_derivation() {
    assert_eq!(account_stark_key('pq', 0, seed().span()), ${pq});
}

#[test]
fn argentx_profile_matches_wallet_derivation() {
    assert_eq!(account_stark_key('argentx', 0, seed().span()), ${argent});
}
`;
writeFileSync(`${OUT}/src/tests.cairo`, tests);
mkdirSync(`${OUT}/args`, { recursive: true });
const shortStr = (s) => "0x" + bytesToHex(enc(s));
for (const [name, profile] of [["braavos", "pq"], ["argentx", "argentx"]]) {
  writeFileSync(`${OUT}/args/${name}.json`, JSON.stringify([shortStr(profile), "0x0", "0x8", ...words, binding]));
}
console.log("seed", hx(seed));
console.log("expected pq (Braavos) key", pq, " argentx key", argent, " binding", binding);
